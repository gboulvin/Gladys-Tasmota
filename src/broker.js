// -----------------------------------------------------------------------------
// Embedded MQTT broker: an Eclipse Mosquitto sub-container (manifest
// `containers`, name `mosquitto`, `start: manual`).
//
// For users without a broker: the integration writes the Mosquitto config and
// password file in the sub-container volume, then starts it. Two accounts:
//   - `gladys`  — the integration itself, random password, never shown;
//   - `tasmota` — the devices, password from the config (or generated).
// The integration reaches the broker by its DNS alias on the private network
// of the integration (`mosquitto:1883`); the devices reach it on the LAN, on
// the host port Gladys assigned (`{{gladys_host}}:{{port:mqtt}}`).
//
// The volume `/config` of the sub-container is mounted from
// `/data/containers/mosquitto/config` in this container (the supervisor
// derives the sub-folder from the container name and the volume path). The
// config lives outside `/mosquitto` on purpose: the image entrypoint chowns
// `/mosquitto` to its own user, which would make the files unwritable here.
// -----------------------------------------------------------------------------

import { randomBytes, pbkdf2Sync } from 'node:crypto';
import { access, mkdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { createLogger } from '@gladysassistant/integration-sdk';

const logger = createLogger({ name: 'broker' });

export const BROKER_CONTAINER = 'mosquitto';
export const BROKER_PORT_NAME = 'mqtt';
export const BROKER_INTERNAL_URL = 'mqtt://mosquitto:1883';
export const BROKER_DEVICE_USER = 'tasmota';
export const BROKER_GLADYS_USER = 'gladys';

/**
 * Mosquitto 2 password hash (`$7$`: PBKDF2-SHA512, the mosquitto_passwd
 * default): `$7$<iterations>$<base64 salt>$<base64 hash>`.
 */
export function hashMosquittoPassword(password, salt = randomBytes(12), iterations = 101) {
  const hash = pbkdf2Sync(password, salt, iterations, 64, 'sha512');
  return `$7$${iterations}$${salt.toString('base64')}$${hash.toString('base64')}`;
}

export function mosquittoConfig() {
  return [
    '# Generated by the Gladys Tasmota integration: edits are overwritten.',
    'listener 1883',
    'allow_anonymous false',
    'password_file /config/passwd',
    'persistence false',
    'log_dest stdout',
    'log_type error',
    'log_type warning',
    'log_type notice',
    '',
  ].join('\n');
}

function generatePassword() {
  return randomBytes(18).toString('base64url');
}

/**
 * Credentials of the embedded broker, kept in /data/broker.json so they
 * survive restarts. The devices password follows the config when set.
 */
export async function loadBrokerCredentials(dataDir, devicePassword) {
  const file = join(dataDir, 'broker.json');
  let stored = {};
  try {
    stored = JSON.parse(await readFile(file, 'utf8'));
  } catch {
    // First start: generated below.
  }
  const credentials = {
    gladysPassword: stored.gladysPassword || generatePassword(),
    devicePassword: devicePassword || stored.devicePassword || generatePassword(),
  };
  const changed =
    credentials.gladysPassword !== stored.gladysPassword ||
    credentials.devicePassword !== stored.devicePassword;
  if (changed) {
    await mkdir(dataDir, { recursive: true });
    await writeFile(file, JSON.stringify(credentials), { mode: 0o600 });
  }
  return { ...credentials, changed };
}

/**
 * Write the broker config, then start (or restart) the sub-container.
 * @returns {Promise<{ url: string, username: string, password: string, devicePassword: string }>}
 *   what the integration connects with
 */
export async function ensureBroker(gladys, { dataDir, devicePassword }) {
  const credentials = await loadBrokerCredentials(dataDir, devicePassword);
  const connection = {
    url: BROKER_INTERNAL_URL,
    username: BROKER_GLADYS_USER,
    password: credentials.gladysPassword,
    devicePassword: credentials.devicePassword,
  };
  const containers = await gladys.getContainers();
  const broker = containers.find((container) => container.name === BROKER_CONTAINER);
  const configDir = join(dataDir, 'containers', BROKER_CONTAINER, 'config');
  const passwdFile = join(configDir, 'passwd');
  // Running with the current passwords already (a Gladys reconnection, a
  // config saved without touching the broker): leave it alone.
  if (broker?.status === 'running' && !credentials.changed && (await exists(passwdFile))) {
    return connection;
  }
  await mkdir(configDir, { recursive: true });
  const passwd = [
    `${BROKER_GLADYS_USER}:${hashMosquittoPassword(credentials.gladysPassword)}`,
    `${BROKER_DEVICE_USER}:${hashMosquittoPassword(credentials.devicePassword)}`,
    '',
  ].join('\n');
  // Readable by the Mosquitto user of the sub-container (another uid).
  await writeFile(passwdFile, passwd, { mode: 0o644 });
  await writeFile(join(configDir, 'mosquitto.conf'), mosquittoConfig(), { mode: 0o644 });

  if (broker?.status === 'running') {
    // The password file was rewritten: reload it.
    await gladys.restartContainer(BROKER_CONTAINER);
  } else {
    await gladys.startContainer(BROKER_CONTAINER);
  }
  logger.info('Embedded MQTT broker started');
  return connection;
}

async function exists(file) {
  try {
    await access(file);
    return true;
  } catch {
    return false;
  }
}

/** Stop the embedded broker (the user switched to another mode). */
export async function stopBroker(gladys) {
  const containers = await gladys.getContainers();
  const broker = containers.find((container) => container.name === BROKER_CONTAINER);
  if (broker && broker.status === 'running') {
    await gladys.stopContainer(BROKER_CONTAINER);
    logger.info('Embedded MQTT broker stopped');
  }
}

/** Host port Gladys assigned to the broker, `null` until it started once. */
export async function brokerHostPort(gladys) {
  const containers = await gladys.getContainers();
  const broker = containers.find((container) => container.name === BROKER_CONTAINER);
  const port = broker?.ports?.find((p) => p.name === BROKER_PORT_NAME || p.container_port === 1883);
  return port?.host_port ?? null;
}
